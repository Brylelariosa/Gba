CHARS = [chr(c) for c in range(32, 127)]


def glyph_rows(ch):
    """Return (width, [8 ints]) with bit7 = leftmost pixel."""
    if ch not in G:
        ch = '?'
    top, rows = G[ch]
    w = max(len(r) for r in rows)
    out = [0] * 8
    for i, r in enumerate(rows):
        y = top + i
        if y > 7:
            continue
        v = 0
        for x, c in enumerate(r):
            if c == '#':
                v |= 0x80 >> x
        out[y] = v
    return w, out


def font_tables():
    widths, rows = [], []
    for ch in CHARS:
        w, r = glyph_rows(ch)
        widths.append(w)
        rows.extend(r)
    return widths, rows


def preview(path, text="The quick brown fox jumps over the lazy dog. 0123456789 ABCDEFGHIJKLMNOPQRSTUVWXYZ HP 120/120 +5 -3 %!? 'x' (y)"):
    W = 480
    scale = 3
    im = Image.new('RGB', (W * scale, 40 * scale), (24, 32, 64))
    px = im.load()
    pen = 2
    y0 = 4
    for ch in text:
        w, rows = glyph_rows(ch)
        for y in range(8):
            for x in range(w):
                if rows[y] & (0x80 >> x):
                    for sy in range(scale):
                        for sx in range(scale):
                            if (pen + x) * scale + sx < im.width:
                                px[(pen + x) * scale + sx, (y0 + y) * scale + sy] = (255, 255, 255)
        pen += w + 1
        if pen > W - 10:
            pen = 2
            y0 += 10
    im.save(path)


